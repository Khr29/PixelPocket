static const u8 BLANK[FONT_H] = { 0, 0, 0, 0, 0, 0, 0 };

const u8 *font_glyph(char c) {
	for (size_t i = 0; i < sizeof(FONT) / sizeof(FONT[0]); i++) {
		if (FONT[i].c == c) {
			return FONT[i].rows;
		}
	}
	return BLANK;
}
